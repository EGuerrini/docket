"""Emit the app's copy of the fit prompt from the pipeline's config, or check it has not drifted.

  python3 emit.py           write app/fit_prompt.json
  python3 emit.py --check   rebuild it in memory and byte-compare with the committed file; exit 1 on drift

CI runs --check on every push. Drift happens when someone edits the prompt file, bumps the model or
the effort in fit_config.py, or hand-edits the JSON, and forgets the other side. Without the check,
the batch path and the live path would quietly send different requests, and every eval of one would
say nothing about the other.
"""
import hashlib
import importlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TARGET = os.path.join(HERE, "app", "fit_prompt.json")


def build(config_module="fit_config"):
    cfg = importlib.import_module(config_module)
    with open(os.path.join(HERE, "prompts", cfg.VERSION_FILE + ".md"), encoding="utf-8") as f:
        system = f.read()
    doc = {
        "_note": "Generated by emit.py from fit_config.py and prompts/. Do not edit: CI fails on drift.",
        "version": cfg.VERSION_FILE,
        "model": cfg.MODEL,
        "effort": cfg.EFFORT,
        "system_sha256": hashlib.sha256(system.encode("utf-8")).hexdigest(),
        "system": system,
    }
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def check(target=TARGET, config_module="fit_config"):
    """None when in sync, else a one-line reason."""
    want = build(config_module)
    try:
        with open(target, encoding="utf-8") as f:
            got = f.read()
    except FileNotFoundError:
        return "%s is missing: run python3 emit.py" % os.path.relpath(target, HERE)
    if got == want:
        return None
    try:
        g, w = json.loads(got), json.loads(want)
        fields = [k for k in w if g.get(k) != w.get(k)] or ["formatting"]
    except ValueError:
        fields = ["not valid JSON"]
    return "%s drifted from fit_config.py and prompts/ (%s): run python3 emit.py and commit both" % (
        os.path.relpath(target, HERE), ", ".join(fields))


def main(argv):
    if "--check" in argv:
        reason = check()
        print(reason or "fit prompt in sync")
        return 1 if reason else 0
    with open(TARGET, "w", encoding="utf-8") as f:
        f.write(build())
    print("wrote", os.path.relpath(TARGET, HERE))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
